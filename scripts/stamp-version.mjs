#!/usr/bin/env node
/**
 * Build version stamper — runs on every `bun run dev` (predev) and
 * `bun run build` (prebuild) so every build carries a distinct version.
 *
 * Derives a git-based version:
 *   base  = package.json "version"          (semver, bumped per milestone)
 *   build = `git rev-list --count HEAD`     (commit count = build number)
 *   sha   = `git rev-parse --short HEAD`
 *
 * Writes src/generated/version.ts (committed fallback: a fresh clone without
 * git hooks still compiles). The file is only rewritten when the derived
 * content actually changes — the Next watcher must never see a no-op touch,
 * otherwise a dev-restart stamp loop would reload the app forever.
 */
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const base = pkg.version || '0.0.0'

function git(args) {
  try {
    return execSync(`git ${args}`, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim()
  } catch {
    return ''
  }
}

const build = Number(git('rev-list --count HEAD') || 0)
const sha = git('rev-parse --short HEAD') || 'dev'
const branch = git('rev-parse --abbrev-ref HEAD') || 'unknown'
const commitDate = git('log -1 --format=%cI') || new Date().toISOString()

const full = build > 0 ? `${base}+${build}.${sha}` : `${base}-dev`
const display = build > 0 ? `v${base}+${build}` : `v${base}-dev`

const body = `// AUTO-GENERATED by scripts/stamp-version.mjs — do not edit by hand.
// Re-stamped on every \`bun run dev\` / \`bun run build\` (predev/prebuild):
// base = package.json version · build = git commit count · sha = HEAD.
export const APP_VERSION = {
  base: '${base}',
  build: ${build},
  sha: '${sha}',
  branch: '${branch}',
  commitDate: '${commitDate}',
  full: '${full}',
  display: '${display}',
} as const

export type AppVersion = typeof APP_VERSION
`

const out = join(root, 'src', 'generated', 'version.ts')
if (!existsSync(out) || readFileSync(out, 'utf8') !== body) {
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, body)
  console.log(`[version] stamped ${display} (${full}) · branch ${branch} · commit ${commitDate}`)
} else {
  console.log(`[version] ${display} up-to-date`)
}
