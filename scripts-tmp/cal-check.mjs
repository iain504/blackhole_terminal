const res = await fetch('http://localhost:3000/api/market/calendar')
const d = await res.json()
const now = Date.now()
const evs = d.events || []
const up = evs.filter((e) => new Date(e.time).getTime() >= now)
console.log('source:', d.source)
console.log('now:', new Date(now).toISOString())
console.log('total:', evs.length, '| upcoming:', up.length)
if (up[0]) console.log('first upcoming:', up[0].time, up[0].country, '-', up[0].event)
else console.log('first upcoming: NONE (all past -> line at bottom)')
console.log('last event:', evs[evs.length - 1]?.time)
