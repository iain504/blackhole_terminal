// Task 89 / Task 3-d — turn the research sweep (scripts-tmp/reco-sweep-results.json,
// FORMAT v2: { version: 2, rows: [...] }) into the baked-in recommendations
// module (src/lib/algo-recommendations.ts).
// Selection (honest-first, shared with the live refresh in algo-reco.ts):
// every symbol×timeframe's rank-1 row with a POSITIVE Calmar-style score,
// then globally best remaining rows until 18 entries; the final list is
// sorted OOS-positive first, then score desc. Rows carry `oos` (walk-forward
// verification) and `boundary` (grid-edge warning).
// Rerun after a fresh sweep: bun scripts-tmp/reco-sweep.ts && bun scripts-tmp/gen-reco.ts
import { readFileSync, writeFileSync } from 'node:fs'
import { pickRecoPicks, RECO_CAP, type RecoComboRow } from '@/lib/algo-reco'

interface Combo {
  symbol: string
  tf: string
  bars: number
  from: number
  to: number
  coveredDays: number
  source: string
  costs: { slip: number; fee: number; spread: number }
  rows: RecoComboRow[]
  error?: string
}

const raw: unknown = JSON.parse(readFileSync('scripts-tmp/reco-sweep-results.json', 'utf8'))
const obj = raw as { version?: unknown; rows?: unknown } | null
if (!obj || typeof obj !== 'object' || Array.isArray(raw) || obj.version !== 2 || !Array.isArray(obj.rows)) {
  console.error('reco-sweep-results.json is not format v2 ({ version: 2, rows: [...] }).')
  console.error('Re-run the sweep first: bun scripts-tmp/reco-sweep.ts (the old bare-array format lacks oos/boundary).')
  process.exit(1)
}
const combos = obj.rows as Combo[]

const picked = pickRecoPicks(
  combos.filter((c) => !c.error && Array.isArray(c.rows) && c.rows.length > 0),
  RECO_CAP,
)

const entries = picked.map(({ combo: p, row }) => ({
  symbol: p.symbol,
  timeframe: p.tf,
  strategy: row.strategy,
  params: row.params,
  slipBps: p.costs.slip,
  feeBps: p.costs.fee,
  spreadBps: p.costs.spread,
  score: row.score,
  netPct: row.netPct,
  pf: row.pf,
  winPct: row.winPct,
  maxDDPct: row.maxDDPct,
  trades: row.trades,
  oos: row.oos,
  boundary: row.boundary,
  bars: p.bars,
  coveredDays: p.coveredDays,
  from: p.from,
  to: p.to,
  source: p.source,
}))

const meta = {
  generatedAt: new Date().toISOString(),
  symbols: [...new Set(combos.map((c) => c.symbol))].join(', '),
  method:
    'Full-catalog sweeps (strategy defaults + auto optimizer grid) per symbol × timeframe at max history per TF (1m 120d / 5m 365d / 15m 730d, feed permitting), ranked by the Backtest panel\'s Calmar-style score (net % ÷ max DD %) with a min-10-trades gate. Task 3-d honesty pass: position size capped at 1× capital per trade (maxNotionalX 1 — no leverage), drawdown is mark-to-market on open positions, crypto is long-only (Alpaca crypto has no shorting), and every winner is walk-forward verified — parameters are tuned on the first 70% of bars (in-sample) then re-run untouched on the final 30% (out-of-sample); rows carry `oos` (null when the OOS window produced < 3 trades) and `boundary: true` when any tuned parameter sits on its grid edge (weakest evidence — the optimum may lie beyond the searched range). Realistic per-market costs baked in: slippage/fee/spread seeded from the Task 88 suggestion table (crypto majors 3/10/3, altcoins 10/10/5, US equities 2/0/2 bps). Config: $10,000 capital · TP 1.5% / SL 1% · max 3 trades/day. net% is the IN-SAMPLE tuned window — always check the OOS fields and re-run on fresh bars before risking money.',
}

const file = `// AUTO-GENERATED by scripts-tmp/gen-reco.ts (Task 89, Task 3-d honesty pass) — do not edit by hand.
// Regenerate: bun scripts-tmp/reco-sweep.ts && bun scripts-tmp/gen-reco.ts
//
// Baked-in "Recommended setups" for the Backtest page: the top full-catalog
// sweep winners across a symbol × timeframe matrix, each carrying the EXACT
// cost model it was measured with so applying one reproduces the honest run.
import type { AlgoStrategyId, AlgoTimeframe } from '@/lib/algo-strategies'

/** Out-of-sample walk-forward verification (Task 3-d) — null when the OOS
 *  window produced < 3 trades. */
export interface AlgoRecoOos {
  netPct: number
  profitFactor: number
  winRate: number
  maxDrawdownPct: number
  trades: number
}

export interface AlgoRecommendation {
  symbol: string
  timeframe: AlgoTimeframe
  strategy: AlgoStrategyId
  params: Record<string, number>
  slipBps: number
  feeBps: number
  spreadBps: number
  score: number
  netPct: number
  pf: number
  winPct: number
  maxDDPct: number
  trades: number
  bars: number
  coveredDays: number
  from: number
  to: number
  source: string
  // Task 3-d (optional so pre-3d baked rows still typecheck):
  // walk-forward OOS re-run of this exact row on the untouched 30% tail
  oos?: AlgoRecoOos | null
  // true when any tuned param sits on its sweep-grid min/max (weak evidence)
  boundary?: boolean
}

export const ALGO_RECO_META = ${JSON.stringify(meta, null, 2)} as const

export const ALGO_RECOMMENDATIONS: AlgoRecommendation[] = ${JSON.stringify(entries, null, 2)}
`
writeFileSync('src/lib/algo-recommendations.ts', file)
const oosPositive = entries.filter((e) => e.oos && e.oos.netPct > 0).length
console.log(`wrote src/lib/algo-recommendations.ts — ${entries.length} recommendations (${oosPositive}/${entries.length} OOS-positive, listed OOS-positive first)`)
for (const e of entries) {
  const oos = e.oos ? `oos ${e.oos.netPct >= 0 ? '+' : ''}${e.oos.netPct}%/${e.oos.trades}t` : 'oos null  '
  console.log(`  ${e.symbol.padEnd(8)} ${e.timeframe} ${e.strategy.padEnd(13)} score ${String(e.score).padStart(6)} net ${String(e.netPct).padStart(8)}% ${oos} ${e.boundary ? 'BOUNDARY' : ''} dd ${e.maxDDPct}% trades ${e.trades}`)
}
