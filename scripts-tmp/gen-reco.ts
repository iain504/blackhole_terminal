// Task 89 — turn the research sweep (scripts-tmp/reco-sweep-results.json) into
// the baked-in recommendations module (src/lib/algo-recommendations.ts).
// Selection: every symbol×timeframe's winning row (rank 1) with a POSITIVE
// Calmar-style score, then globally best remaining rows until 18 entries.
// Rerun after a fresh sweep: bun scripts-tmp/gen-reco.ts
import { readFileSync, writeFileSync } from 'node:fs'

interface Row {
  strategy: string
  params: Record<string, number>
  score: number
  netPct: number
  pf: number
  winPct: number
  maxDDPct: number
  trades: number
}
interface Combo {
  symbol: string
  tf: string
  bars: number
  from: number
  to: number
  coveredDays: number
  source: string
  costs: { slip: number; fee: number; spread: number }
  rows: Row[]
  error?: string
}

const CAP = 18
const combos: Combo[] = JSON.parse(readFileSync('scripts-tmp/reco-sweep-results.json', 'utf8'))

const winners: (Combo & { row: Row })[] = []
const pool: (Combo & { row: Row })[] = []
for (const c of combos) {
  if (c.error || !Array.isArray(c.rows) || c.rows.length === 0) continue
  const [best, ...rest] = c.rows
  if (best.score > 0) winners.push({ ...c, row: best })
  for (const r of rest) if (r.score > 0) pool.push({ ...c, row: r })
}
pool.sort((a, b) => b.row.score - a.row.score)
const picked = [...winners, ...pool].slice(0, CAP)
picked.sort((a, b) => b.row.score - a.row.score)

const entries = picked.map((p) => ({
  symbol: p.symbol,
  timeframe: p.tf,
  strategy: p.row.strategy,
  params: p.row.params,
  slipBps: p.costs.slip,
  feeBps: p.costs.fee,
  spreadBps: p.costs.spread,
  score: p.row.score,
  netPct: p.row.netPct,
  pf: p.row.pf,
  winPct: p.row.winPct,
  maxDDPct: p.row.maxDDPct,
  trades: p.row.trades,
  bars: p.bars,
  coveredDays: p.coveredDays,
  from: p.from,
  to: p.to,
  source: p.source,
}))

const meta = {
  generatedAt: new Date().toISOString(),
  symbols: [...new Set(combos.map((c) => c.symbol))].join(', '),
  method:
    'Full-catalog sweeps (strategy defaults + auto optimizer grid) per symbol × timeframe at max history per TF (1m 120d / 5m 365d / 15m 730d, feed permitting), ranked by the Backtest panel\'s Calmar-style score (net % ÷ max DD %) with a min-10-trades gate. Realistic per-market costs baked in: slippage/fee/spread seeded from the Task 88 suggestion table (crypto majors 3/10/3, altcoins 10/10/5, US equities 2/0/2 bps). Config: qty 10 · $10,000 capital · TP 1.5% / SL 1% · max 3 trades/day. IN-SAMPLE historical results — always re-run on fresh bars and check the drawdown before risking money.',
}

const file = `// AUTO-GENERATED by scripts-tmp/gen-reco.ts (Task 89) — do not edit by hand.
// Regenerate: bun scripts-tmp/reco-sweep.ts && bun scripts-tmp/gen-reco.ts
//
// Baked-in "Recommended setups" for the Backtest page: the top full-catalog
// sweep winners across a symbol × timeframe matrix, each carrying the EXACT
// cost model it was measured with so applying one reproduces the honest run.
import type { AlgoStrategyId, AlgoTimeframe } from '@/lib/algo-strategies'

export interface AlgoRecommendation {
  symbol: string
  timeframe: AlgoTimeframe
  strategy: AlgoStrategyId
  params: Record<string, number>
  slipBps: number
  feeBps: number
  spreadBps: number
  score: number
  netPct: number
  pf: number
  winPct: number
  maxDDPct: number
  trades: number
  bars: number
  coveredDays: number
  from: number
  to: number
  source: string
}

export const ALGO_RECO_META = ${JSON.stringify(meta, null, 2)} as const

export const ALGO_RECOMMENDATIONS: AlgoRecommendation[] = ${JSON.stringify(entries, null, 2)}
`
writeFileSync('src/lib/algo-recommendations.ts', file)
console.log(`wrote src/lib/algo-recommendations.ts — ${entries.length} recommendations (winners: ${winners.length}, pool filled: ${picked.length - winners.length})`)
for (const e of entries) {
  console.log(`  ${e.symbol.padEnd(8)} ${e.timeframe} ${e.strategy.padEnd(13)} score ${String(e.score).padStart(6)} net ${String(e.netPct).padStart(8)}% pf ${e.pf} dd ${e.maxDDPct}% trades ${e.trades}`)
}
